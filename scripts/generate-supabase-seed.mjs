import { writeFile } from 'node:fs/promises';
import { build } from 'vite';

const assetPaths = {
  appono: {
    logo: 'appono/logo.png', team: 'appono/team.jpg',
    members: ['appono/members/guilherme-yuji.jpg', 'appono/members/davi-janusz.jpg', 'appono/members/joao-victor.jpg'],
  },
  selectio: {
    logo: 'selectio/logo.png', team: 'selectio/team.png',
    members: ['selectio/members/kalil-barreto.png', 'selectio/members/gustavo-amorim.png', 'selectio/members/marcos-peyerl.png'],
  },
  bixuco: {
    logo: 'bixuco/logo.png', team: 'bixuco/team.png',
    members: ['bixuco/members/arthur-regiani.png', 'bixuco/members/sophia-freitas.png', 'bixuco/members/yasmin-bertoni.png'],
  },
  facos: { logo: 'facos/logo.svg', team: null, members: [] },
  condomit: { logo: 'condomit/logo.png', team: null, members: [null, null, null] },
  recure: {
    logo: 'recure/logo.png', team: 'recure/team.jpg',
    members: ['recure/members/fernando-bolonha.jpg', 'recure/members/pedro-de-macedo.jpg', 'recure/members/rafael-rodrigues.jpg', 'recure/members/daniel-martins.jpg'],
  },
};

const quote = (value) => value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;

const buildResult = await build({
  configFile: false,
  plugins: [{
    name: 'seed-entry',
    resolveId(id) { return id.endsWith('virtual:startup-seed') ? '\0virtual:startup-seed' : null; },
    load(id) { return id === '\0virtual:startup-seed' ? "export { startupsByYear } from '/src/data/startups.js';" : null; },
  }],
  build: { ssr: 'virtual:startup-seed', write: false },
});

const entry = buildResult.output.find((item) => item.type === 'chunk' && item.isEntry);
const { startupsByYear } = await import(`data:text/javascript;base64,${Buffer.from(entry.code).toString('base64')}`);
const lines = [
  '-- Generated by scripts/generate-supabase-seed.mjs. Do not edit manually.',
  '-- Upload the objects listed in supabase/storage-manifest.md before running this file.',
  '',
];

for (const [year, startups] of Object.entries(startupsByYear)) {
  for (const startup of startups) {
    const assets = assetPaths[startup.id];
    const values = [
      quote(startup.id), quote(year), quote(startup.number), quote(startup.name), quote(startup.category), quote(startup.accent),
      json(startup.tags), json(startup.description), json(startup.tagline), json(startup.segment), json(startup.headline),
      json(startup.paragraphs), json(startup.features), json(startup.socials), quote(assets.logo), quote(assets.team), Number(startup.number),
    ].join(', ');
    lines.push(`insert into public.startups (slug, cohort_year, display_number, name, category, accent, tags, description, tagline, segment, headline, paragraphs, features, socials, logo_url, team_image_url, sort_order)`);
    lines.push(`values (${values})`);
    lines.push(`on conflict (slug) do update set cohort_year = excluded.cohort_year, display_number = excluded.display_number, name = excluded.name, category = excluded.category, accent = excluded.accent, tags = excluded.tags, description = excluded.description, tagline = excluded.tagline, segment = excluded.segment, headline = excluded.headline, paragraphs = excluded.paragraphs, features = excluded.features, socials = excluded.socials, logo_url = excluded.logo_url, team_image_url = excluded.team_image_url, sort_order = excluded.sort_order;`);
    lines.push(`delete from public.startup_members where startup_id = (select id from public.startups where slug = ${quote(startup.id)});`);

    startup.teamMembers.forEach((member, index) => {
      const memberValues = [
        `(select id from public.startups where slug = ${quote(startup.id)})`, quote(member.name), json(member.role), quote(assets.members[index]),
        quote(member.instagram), quote(member.github), quote(member.linkedin), quote(member.email), index + 1,
      ].join(', ');
      lines.push('insert into public.startup_members (startup_id, name, role, image_url, instagram, github, linkedin, email, sort_order)');
      lines.push(`values (${memberValues});`);
    });
    lines.push('');
  }
}

await writeFile('supabase/seed.sql', `${lines.join('\n')}\n`);
console.log('Generated supabase/seed.sql from src/data/startups.js.');
